// 病害名列表（下拉用，顺序即上表声明顺序）
const DISEASE_NAMES = Object.keys(DISEASE_ADVICE)

/** 取某病害的打药建议，未选中返回 null */
function getAdvice(name) {
  return DISEASE_ADVICE[name] || null
}

/** 拼一行摘要，用于卡片副标题 */
function adviceMeta(name) {
  const a = getAdvice(name)
  if (!a) return ''
  return '推荐：' + (a.pesticide || '无需施药') + ' · ' + (a.dose || '—') + ' · 间隔 ' + a.phi
}

